-- The RoleName enum + @Enumerated(STRING) is the guard now; drop the baked-in CHECK so
-- new role values don't need a schema change each time.
ALTER TABLE roles DROP CONSTRAINT IF EXISTS roles_name_check;

INSERT INTO roles (name) SELECT 'ROLE_USER_ADMIN'
  WHERE NOT EXISTS (SELECT 1 FROM roles WHERE name = 'ROLE_USER_ADMIN');
INSERT INTO roles (name) SELECT 'ROLE_MASTER_ADMIN'
  WHERE NOT EXISTS (SELECT 1 FROM roles WHERE name = 'ROLE_MASTER_ADMIN');

CREATE TABLE IF NOT EXISTS custom_field_definitions (
    id            bigint generated by default as identity primary key,
    version       bigint       not null default 0,
    company_id    bigint       not null references companies (id),
    resource      varchar(60)  not null,
    field_key     varchar(60)  not null,
    label         varchar(120) not null,
    data_type     varchar(20)  not null,
    max_length    integer,
    min_value     numeric(18,4),
    max_value     numeric(18,4),
    required      boolean      not null default false,
    unique_value  boolean      not null default false,
    section       varchar(60),
    display_order integer      not null default 0,
    options       jsonb,
    active        boolean      not null default true,
    created_at    timestamp(6),
    updated_at    timestamp(6)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_cfd_company_resource_key
    ON custom_field_definitions (company_id, resource, lower(field_key));
CREATE INDEX IF NOT EXISTS idx_cfd_lookup
    ON custom_field_definitions (company_id, resource, active, display_order);

